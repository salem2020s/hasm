#!/usr/bin/env node
// Deterministic generator for the two migrations of "audit head integrity", slice 1, option (a) of docs/AUDIT-HEAD-INTEGRITY-PLAN.md: a BEFORE INSERT trigger that makes every row of an audit table link to the
// head of its stream (the SYSTEM audit table t_7e93ef23 and the BUSINESS audit table of every company database). SINGLE SOURCE for both: the two SQL templates below, written with LOGICAL tokens such as
// {{AuditHeadLink.FnSystemLink}}. Every opaque physical name (D-029) is derived as
//   prefix + first 8 hex digits of SHA-256("hasm.audit-head-link.v1:" + token)
// The seed deliberately does NOT contain a migration number: the numbers are assigned by the lead at the final round, so the names never change when the files are renumbered.
// References to names that already exist (the audit tables and their columns: system migration 0005, company migration 0002) are written [[Entity.Name]] and resolved from the committed dictionaries.
// Usage:  node tools/schema/audit-head-link.cjs --write | --check
// RENUMBERING at merge: change SYSTEM_FILE and COMPANY_FILE below, re-run --write, and update the pinned migration counts and Version constants in the tests.
const fs = require("fs");
const path = require("path");
const crypto = require("crypto");

const SYSTEM_FILE = "0036_audit_head_link.sql";           // PROVISIONAL number: renamed at the final round
const COMPANY_FILE = "0037_company_audit_head_link.sql";   // PROVISIONAL number: renamed at the final round
const root = path.resolve(__dirname, "..", "..");
const infra = path.join(root, "src", "backend", "Hasm.Infrastructure");
const outSystemSql = path.join(infra, "SystemDatabase", "Migrations", SYSTEM_FILE);
const outCompanySql = path.join(infra, "CompanyDatabase", "Migrations", COMPANY_FILE);
const outSystemCs = path.join(infra, "SystemDatabase", "SystemSchema.AuditHeadLink.cs");
const outCompanyCs = path.join(infra, "CompanyDatabase", "CompanySchema.AuditHeadLink.cs");

function parseDictionary(dir, file) {
  const text = fs.readFileSync(path.join(infra, dir, file), "utf8");
  const map = new Map();
  for (const m of text.matchAll(/public static class (\w+)\s*\{([\s\S]*?)\n    \}/g))
    for (const c of m[2].matchAll(/public const string (\w+) = "([tcfkr]_[0-9a-f]{8})";/g)) map.set(`${m[1]}.${c[1]}`, c[2]);
  return map;
}
const SYSTEM_EXISTING = parseDictionary("SystemDatabase", "SystemSchema.cs");
const COMPANY_EXISTING = parseDictionary("CompanyDatabase", "CompanySchema.cs");
const resolver = (existing) => (key) => { const v = existing.get(key); if (!v) throw new Error("unknown existing name " + key); return v; };

// The function is written ONCE per database kind from one template. Every relation is schema-qualified (public.<table>) and the variables take their types from the qualified columns (%TYPE), so no
// unqualified relation or type name is left that a pg_temp object could shadow (review Y1 of PR 228); the functions used (sha256, convert_to, decode) are called unqualified, which the guard requires and which
// pg_temp can never shadow (the temporary schema is not searched for functions or operators). The genesis expression is exactly AuditCanonical.GenesisHash: SHA-256 of "HASM-AUDIT-GENESIS-v1", a NUL byte and the
// stream key (review Y2): a text value cannot hold a NUL and the guard forbids backslash literals, hence decode('00', 'hex').
const template = (kind, fn, tr, E) => `-- Migration (${kind}): the link guard of the audit head, slice 1 of docs/AUDIT-HEAD-INTEGRITY-PLAN.md (option (a)). Forward-only and ADDITIVE: one new trigger function and one new BEFORE INSERT trigger on the audit table
-- of ${kind === "system" ? "the SYSTEM database (the system stream and every company access stream)" : "every company database (the stream business:<company id>)"}. Nothing existing is dropped, replaced, disabled or modified (the append-only function and triggers stay exactly as they are),
-- nothing is seeded and no existing row is read or validated: the trigger applies to LATER inserts only. Opaque physical names (D-029) are generated by tools/schema/audit-head-link.cjs (logical dictionary:
-- ${kind === "system" ? "SystemSchema.AuditHeadLink.cs" : "CompanySchema.AuditHeadLink.cs"}). Do not edit by hand: re-run the generator.
--
-- WHAT THIS IS: every inserted row must continue the chain of ITS stream: when the stream is empty the row has sequence 1 and the genesis hash as its previous hash; otherwise it has the head's sequence plus one and the
-- head's hash as its previous hash. Anything else (a gap, a replay of an old sequence, an unlinked or random previous hash, a wrong genesis, a hidden insertion into the middle of a chain) is refused with the message
-- audit_link_violation and nothing is written. The head is the row with the greatest sequence of the stream (a primary-key lookup, under the writer's own per-stream lock).
-- WHAT THIS IS NOT: a defence against a forged row at the END of a chain. The key that authenticates a record never enters the database, so a holder of the runtime credentials can still read the head, link a
-- new row to it and give it a bad authentication code: that row passes this guard (the plan states this limit; recovery is a later slice). What the guard guarantees is that any such damage is a CONTIGUOUS TAIL.
-- NO SHADOWING: the function runs with the rights of the inserting session. Every relation is written public.<table> and the variable types are taken from the qualified columns, so a temporary object of the
-- same name cannot stand in for the table or the type.

CREATE FUNCTION ${fn}() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    head_seq public.[[${E}.Table]].[[${E}.Seq]]%TYPE;
    head_hash public.[[${E}.Table]].[[${E}.Hash]]%TYPE;
BEGIN
    SELECT h.[[${E}.Seq]], h.[[${E}.Hash]] INTO head_seq, head_hash
    FROM public.[[${E}.Table]] AS h
    WHERE h.[[${E}.StreamKey]] = NEW.[[${E}.StreamKey]]
    ORDER BY h.[[${E}.Seq]] DESC
    LIMIT 1;
    IF NOT FOUND THEN
        IF NEW.[[${E}.Seq]] <> 1
           OR NEW.[[${E}.PrevHash]] IS DISTINCT FROM sha256(convert_to('HASM-AUDIT-GENESIS-v1', 'UTF8') || decode('00', 'hex') || convert_to(NEW.[[${E}.StreamKey]], 'UTF8')) THEN
            RAISE EXCEPTION 'audit_link_violation';
        END IF;
    ELSIF NEW.[[${E}.Seq]] <> head_seq + 1 OR NEW.[[${E}.PrevHash]] IS DISTINCT FROM head_hash THEN
        RAISE EXCEPTION 'audit_link_violation';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER ${tr} BEFORE INSERT ON [[${E}.Table]] FOR EACH ROW EXECUTE FUNCTION ${fn}();
`;
const systemTemplate = template("system", "{{AuditHeadLink.FnSystemLink}}", "{{AuditHeadLink.TrSystemLink}}", "AuditEvent");
const companyTemplate = template("company", "{{AuditHeadLink.FnBusinessLink}}", "{{AuditHeadLink.TrBusinessLink}}", "BusinessAudit");

const prefixOf = (token) => { const last = token.split(".").pop(); return /^Fn[A-Z]/.test(last) ? "f_" : /^Tr[A-Z]/.test(last) ? "r_" : "c_"; };
const physical = (token) => prefixOf(token) + crypto.createHash("sha256").update("hasm.audit-head-link.v1:" + token).digest("hex").slice(0, 8);

function existingNames() {
  const names = new Set();
  const own = new Set([outSystemSql, outCompanySql, outSystemCs, outCompanyCs]);
  const scan = (dir) => {
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
      const p = path.join(dir, e.name);
      if (e.isDirectory()) { if (e.name !== "bin" && e.name !== "obj") scan(p); continue; }
      if (own.has(p) || !/\.(sql|cs)$/.test(e.name)) continue;
      for (const m of fs.readFileSync(p, "utf8").matchAll(/\b[tcfkr]_[0-9a-f]{8}\b/g)) names.add(m[0]);
    }
  };
  scan(path.join(infra, "CompanyDatabase")); scan(path.join(infra, "SystemDatabase"));
  return names;
}

function csFile(ns, generatorNote, prefixMembers, mapName, tokens, byToken) {
  let cs = `namespace Hasm.Infrastructure.${ns};\n\n// GENERATED by tools/schema/audit-head-link.cjs for the ${generatorNote} migration of the audit head link guard (slice 1 of docs/AUDIT-HEAD-INTEGRITY-PLAN.md). Do not edit: re-run the generator.\n` +
    "// Physical names are opaque (D-029), derived deterministically from the logical token (the seed does not contain the migration number), and fixed: changing one requires a new migration.\n" +
    `// AuditHeadLink names the one trigger function and the one trigger of that migration (no table).\npublic static partial class ${ns === "SystemDatabase" ? "SystemSchema" : "CompanySchema"}\n{\n    public static class AuditHeadLink\n    {\n`;
  for (const t of tokens) cs += `        public const string ${t.split(".")[1]} = "${byToken.get(t)}";\n`;
  cs += `    }\n\n    private static IReadOnlyDictionary<string, string> ${mapName} { get; } = new Dictionary<string, string>\n    {\n`;
  for (const t of tokens) cs += `        ["${t}"] = AuditHeadLink.${t.split(".")[1]},\n`;
  cs += "    };\n}\n";
  return cs;
}

function generate() {
  const render = (tpl, existing) => tpl.replace(/\[\[([A-Za-z0-9.]+)\]\]/g, (_, k) => resolver(existing)(k));
  const sysBody = render(systemTemplate, SYSTEM_EXISTING), coBody = render(companyTemplate, COMPANY_EXISTING);
  const tokensOf = (b) => [...new Set([...b.matchAll(/\{\{([A-Za-z0-9.]+)\}\}/g)].map((m) => m[1]))];
  const sysTokens = tokensOf(sysBody), coTokens = tokensOf(coBody);
  const taken = existingNames(), byToken = new Map(), seen = new Map();
  for (const t of [...sysTokens, ...coTokens]) {
    const name = physical(t);
    if (taken.has(name)) throw new Error(`collision with an existing name: ${t} -> ${name}`);
    if (seen.has(name)) throw new Error(`collision inside the migrations: ${t} and ${seen.get(name)} -> ${name}`);
    seen.set(name, t); byToken.set(t, name);
  }
  const fill = (b) => b.replace(/\{\{([A-Za-z0-9.]+)\}\}/g, (_, t) => byToken.get(t));
  return {
    systemSql: fill(sysBody), companySql: fill(coBody),
    systemCs: csFile("SystemDatabase", "system", true, "AuditHeadLinkMap", sysTokens, byToken),
    companyCs: csFile("CompanyDatabase", "company", true, "AuditHeadLinkMap", coTokens, byToken),
  };
}

const g = generate();
const mode = process.argv[2];
if (mode === "--write") {
  fs.writeFileSync(outSystemSql, g.systemSql); fs.writeFileSync(outCompanySql, g.companySql); fs.writeFileSync(outSystemCs, g.systemCs); fs.writeFileSync(outCompanyCs, g.companyCs); console.log("written");
} else if (mode === "--check") {
  const norm = (s) => s.replace(/\r\n/g, "\n");
  const same = (p, c) => fs.existsSync(p) && norm(fs.readFileSync(p, "utf8")) === c;
  if (!(same(outSystemSql, g.systemSql) && same(outCompanySql, g.companySql) && same(outSystemCs, g.systemCs) && same(outCompanyCs, g.companyCs))) { console.error("generated audit head link schema differs from the committed files"); process.exit(1); }
  console.log("audit head link schema files match the generator");
} else { console.error("usage: --write | --check"); process.exit(2); }
