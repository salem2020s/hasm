#!/usr/bin/env node
// Deterministic generator for the SYSTEM migration of identity integrity slice S-2c (part 1) (docs/IDENTITY-INTEGRITY-PLAN.md, register item SEC-RT-SESSION): the append-only IdentityAnchor table and the margin of the challenge delete guard.
// SINGLE SOURCE: the SQL template below, written with LOGICAL tokens such as {{SessionIntegrity.Tag}}. Every opaque physical name (D-029) is derived as
//   prefix + first 8 hex digits of SHA-256("hasm.system.identity-anchor.v1:" + token)
// The seed deliberately does NOT contain the migration number: the number is assigned when the slice merges (the next free system number), so the names never change when the file is renumbered.
// References to names that already exist (the session and user tables, written [[MfaChallenge.Table]]) are written [[Entity.Name]] and resolved from the committed system dictionaries, never re-derived.
// Usage:  node tools/schema/system-identity-anchor.cjs --write | --check
// RENUMBERING at merge: change MIGRATION_FILE below, re-run --write, and update the pinned migration counts in the tests (the journal count assertions).
const fs = require("fs");
const path = require("path");
const crypto = require("crypto");

const MIGRATION_FILE = "0040_append_only_anchor_history.sql";   // PROVISIONAL number: renamed at merge time (see above)
const root = path.resolve(__dirname, "..", "..");
const infra = path.join(root, "src", "backend", "Hasm.Infrastructure");
const outSql = path.join(infra, "SystemDatabase", "Migrations", MIGRATION_FILE);
const outCs = path.join(infra, "SystemDatabase", "SystemSchema.IdentityAnchor.cs");

function parseDictionary(file) {
  const text = fs.readFileSync(path.join(infra, "SystemDatabase", file), "utf8");
  const map = new Map();
  for (const m of text.matchAll(/public static class (\w+)\s*\{([\s\S]*?)\n    \}/g))
    for (const c of m[2].matchAll(/public const string (\w+) = "([tcfkr]_[0-9a-f]{8})";/g)) map.set(`${m[1]}.${c[1]}`, c[2]);
  return map;
}
const EXISTING = new Map([...parseDictionary("SystemSchema.cs"), ...parseDictionary("SystemSchema.MfaLogin.cs")]);
const ext = (key) => { const v = EXISTING.get(key); if (!v) throw new Error("unknown existing name " + key); return v; };

const TEMPLATE = `-- Migration (system): identity integrity slice S-2c part 1 (docs/IDENTITY-INTEGRITY-PLAN.md section 5, owner decision OD-4). Forward-only and ADDITIVE: one new append-only table, one new trigger on the challenge table.
-- Nothing existing is dropped, replaced, disabled or modified, nothing is seeded and no setting is touched. Opaque physical names (D-029) are generated by tools/schema/system-identity-anchor.cjs (logical dictionary:
-- SystemSchema.IdentityAnchor.cs). Do not edit by hand: re-run the generator.
--
-- WHAT THIS IS: the identity anchor is an append-only history: one row per security change of an identity record (kind, subject, revision), each with a key id and a tag computed by the API with a key the database does
-- not hold. The API honours only anchors whose tag verifies and takes the highest valid revision as the lower bound of the record: an older, once-valid record written back is refused, and a junk anchor (a bad tag, an
-- unknown key id) can never raise the bound, it is ignored and reported. The table can only grow: no update and no delete (a guard trigger; the runtime account holds SELECT and INSERT only).

CREATE TABLE {{IdentityAnchor}} (
    {{IdentityAnchor.Id}} uuid NOT NULL,
    {{IdentityAnchor.Kind}} smallint NOT NULL,
    {{IdentityAnchor.SubjectId}} uuid NOT NULL,
    {{IdentityAnchor.Revision}} bigint NOT NULL,
    {{IdentityAnchor.KeyId}} varchar(32) NOT NULL,
    {{IdentityAnchor.Tag}} bytea NOT NULL,
    {{IdentityAnchor.CreatedAtUtc}} timestamptz NOT NULL,
    CONSTRAINT {{IdentityAnchor.Pk}} PRIMARY KEY ({{IdentityAnchor.Id}}),
    CONSTRAINT {{IdentityAnchor.CkShape}} CHECK ({{IdentityAnchor.Kind}} >= 0 AND {{IdentityAnchor.Revision}} >= 0 AND octet_length({{IdentityAnchor.Tag}}) = 32 AND {{IdentityAnchor.KeyId}} ~ '^[a-z0-9][a-z0-9-]{0,31}$')
);
CREATE INDEX {{IdentityAnchor.IxSubject}} ON {{IdentityAnchor}} ({{IdentityAnchor.Kind}}, {{IdentityAnchor.SubjectId}}, {{IdentityAnchor.Revision}} DESC);

CREATE FUNCTION {{IdentityAnchor.FnAppendOnly}}() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'the identity anchor history is append-only';
END;
$$;
CREATE TRIGGER {{IdentityAnchor.TrAppendOnly}} BEFORE UPDATE OR DELETE ON {{IdentityAnchor}} FOR EACH ROW EXECUTE FUNCTION {{IdentityAnchor.FnAppendOnly}}();
REVOKE ALL ON TABLE {{IdentityAnchor}} FROM PUBLIC;

-- Review L3 of PR 237: the delete guard of the challenge table (migration 0039) refuses to delete a challenge that has not expired. This SECOND trigger adds a margin of one hour, so a clock difference between the
-- application and the database can never let a live challenge be deleted. Both guards apply, so the effective rule is the stricter one; the guard of 0039 is not replaced.
CREATE FUNCTION {{ChallengeGuard.FnMargin}}() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF OLD.[[MfaChallenge.ExpiresAtUtc]] >= clock_timestamp() - interval '1 hour' THEN
        RAISE EXCEPTION 'a challenge is not deleted until it has been expired for an hour';
    END IF;
    RETURN OLD;
END;
$$;
CREATE TRIGGER {{ChallengeGuard.TrMargin}} BEFORE DELETE ON [[MfaChallenge.Table]] FOR EACH ROW EXECUTE FUNCTION {{ChallengeGuard.FnMargin}}();
`;
function prefixOf(token) {
  const last = token.split(".").pop();
  if (!token.includes(".")) return "t_";
  if (/^Fn[A-Z]/.test(last)) return "f_";
  if (/^Tr[A-Z]/.test(last)) return "r_";
  if (/^(Pk|Uq|Fk|Ck|Ix)([A-Z]|$)/.test(last)) return "k_";
  return "c_";
}
const physical = (token) => prefixOf(token) + crypto.createHash("sha256").update("hasm.system.identity-anchor.v1:" + token).digest("hex").slice(0, 8);

function existingNames() {
  const names = new Set();
  const scan = (dir) => {
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
      const p = path.join(dir, e.name);
      if (e.isDirectory()) { if (e.name !== "bin" && e.name !== "obj") scan(p); continue; }
      if (p === outSql || p === outCs) continue;
      if (!/\.(sql|cs)$/.test(e.name)) continue;
      for (const m of fs.readFileSync(p, "utf8").matchAll(/\b[tcfkr]_[0-9a-f]{8}\b/g)) names.add(m[0]);
    }
  };
  scan(path.join(infra, "CompanyDatabase")); scan(path.join(infra, "SystemDatabase"));
  return names;
}

function generate() {
  const body = TEMPLATE.replace(/\[\[([A-Za-z0-9.]+)\]\]/g, (_, k) => ext(k));
  const tokens = [...new Set([...body.matchAll(/\{\{([A-Za-z0-9.]+)\}\}/g)].map((m) => m[1]))];
  const taken = existingNames();
  const byToken = new Map(), seen = new Map();
  for (const t of tokens) {
    const name = physical(t);
    if (taken.has(name)) throw new Error(`collision with an existing name: ${t} -> ${name}`);
    if (seen.has(name)) throw new Error(`collision inside the migration: ${t} and ${seen.get(name)} -> ${name}`);
    seen.set(name, t); byToken.set(t, name);
  }
  const sql = body.replace(/\{\{([A-Za-z0-9.]+)\}\}/g, (_, t) => byToken.get(t));
  const entities = [...new Set(tokens.map((t) => t.split(".")[0]))];
  let cs = "namespace Hasm.Infrastructure.SystemDatabase;\n\n// GENERATED by tools/schema/system-identity-anchor.cjs for the system migration of the identity integrity slice S-2c (part 1). Do not edit: re-run the generator.\n" +
    "// Physical names are opaque (D-029), derived deterministically from the logical token (the seed does not contain the migration number), and fixed: changing one requires a new migration.\n" +
    "// IdentityAnchor names the new table, its columns, constraints, index, function and trigger; ChallengeGuard names the margin trigger of the challenge table.\npublic static partial class SystemSchema\n{\n";
  for (const e of entities) {
    cs += `    public static class ${e}\n    {\n`;
    if (byToken.has(e)) cs += `        public const string Table = "${byToken.get(e)}";\n`;
    for (const t of tokens.filter((x) => x.startsWith(e + "."))) cs += `        public const string ${t.slice(e.length + 1)} = "${byToken.get(t)}";\n`;
    cs += "    }\n\n";
  }
  cs += "    private static IReadOnlyDictionary<string, string> IdentityAnchorMap { get; } = new Dictionary<string, string>\n    {\n";
  for (const t of tokens) cs += `        ["${t.includes(".") ? t : t + ".Table"}"] = ${t.includes(".") ? t : t + ".Table"},\n`;
  cs += "    };\n}\n";
  return { sql, cs };
}

const { sql, cs } = generate();
const mode = process.argv[2];
if (mode === "--write") { fs.writeFileSync(outSql, sql); fs.writeFileSync(outCs, cs); console.log("written"); }
else if (mode === "--check") {
  const norm = (s) => s.replace(/\r\n/g, "\n");
  const ok = fs.existsSync(outSql) && fs.existsSync(outCs) && norm(fs.readFileSync(outSql, "utf8")) === sql && norm(fs.readFileSync(outCs, "utf8")) === cs;
  if (!ok) { console.error("generated identity anchor schema differs from the committed files"); process.exit(1); }
  console.log("identity anchor schema files match the generator");
} else { console.error("usage: --write | --check"); process.exit(2); }
