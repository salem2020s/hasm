#!/usr/bin/env node
// Deterministic generator for the SYSTEM migration of the second part of owner decision D-235 (M2-TOTP): an owner-only guard on the TOTP secret material.
// SINGLE SOURCE: the SQL template below, written with LOGICAL tokens such as {{TotpGuard.FnOwnerOnly}}. Every opaque physical name (D-029) is derived as
//   prefix + first 8 hex digits of SHA-256("hasm.system.totp-owner-only.v1:" + token)
// The seed deliberately does NOT contain the migration number: the number is assigned when the slice merges (the next free system number), so the names never change when the file is renumbered.
// References to names that already exist (the TOTP table and its columns, system migration 0031) are written [[Entity.Name]] and resolved from the committed system dictionaries, never re-derived.
// Usage:  node tools/schema/system-totp-owner-only.cjs --write | --check
// RENUMBERING at merge: change MIGRATION_FILE below, re-run --write, and update the pinned migration counts in the tests (the journal count assertions).
const fs = require("fs");
const path = require("path");
const crypto = require("crypto");

const MIGRATION_FILE = "0035_totp_owner_only_trigger.sql";   // PROVISIONAL number: renamed at merge time (see above)
const root = path.resolve(__dirname, "..", "..");
const infra = path.join(root, "src", "backend", "Hasm.Infrastructure");
const outSql = path.join(infra, "SystemDatabase", "Migrations", MIGRATION_FILE);
const outCs = path.join(infra, "SystemDatabase", "SystemSchema.TotpGuard.cs");

function parseDictionary(file) {
  const text = fs.readFileSync(path.join(infra, "SystemDatabase", file), "utf8");
  const map = new Map();
  for (const m of text.matchAll(/public static class (\w+)\s*\{([\s\S]*?)\n    \}/g))
    for (const c of m[2].matchAll(/public const string (\w+) = "([tcfkr]_[0-9a-f]{8})";/g)) map.set(`${m[1]}.${c[1]}`, c[2]);
  return map;
}
const EXISTING = new Map([...parseDictionary("SystemSchema.Mfa.cs")]);
const ext = (key) => { const v = EXISTING.get(key); if (!v) throw new Error("unknown existing name " + key); return v; };

const TEMPLATE = `-- Migration (system): owner-only guard on the TOTP secret material (second part of owner decision D-235, register item M2-TOTP; docs/DEVELOPMENT.md "System runtime account"). Forward-only and ADDITIVE: one new
-- trigger function and one new BEFORE UPDATE trigger on the TOTP table. Nothing existing is dropped, replaced, disabled or modified (the function of migration 0031 and its transaction-local rewrap flag stay exactly as
-- they are and remain a second layer), nothing is seeded, no catalog table is written and no setting is touched. Opaque physical names (D-029) are generated by tools/schema/system-totp-owner-only.cjs (logical
-- dictionary: SystemSchema.TotpGuard.cs). Do not edit by hand: re-run the generator.
--
-- WHAT THIS IS: a change of the protected secret material (cipher, nonce, tag, key id) is refused unless the role that runs the statement is the OWNER of the table or a MEMBER of it. The runtime account of the API is
-- neither, so even if it were wrongly granted UPDATE on those columns, and whatever the session flag of the rewrap procedure says, it can never replace a secret: rewrap is an owner-account operation.
-- HOW THE OWNER IS RECOGNISED without naming it (the migration cannot know the owner's name, and a function that reads the catalog tables is not allowed): the information_schema view of table privileges lists, for a
-- table, a row granted by a role to ITSELF only for the owner (the implicit privileges of an owner are held by the owner as its own grantor), and it shows a row only to the role concerned and to the roles that are members
-- of it. So the check below finds such a row for the owner and for a member of the owner, and finds none for any other role: the answer for every role that is not the owner or a member is "no", which refuses.
-- A superuser sees every row and passes (a superuser bypasses every privilege anyway).

CREATE FUNCTION {{TotpGuard.FnOwnerOnly}}() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.[[UserTotp.Cipher]] IS DISTINCT FROM OLD.[[UserTotp.Cipher]] OR NEW.[[UserTotp.Nonce]] IS DISTINCT FROM OLD.[[UserTotp.Nonce]]
       OR NEW.[[UserTotp.Tag]] IS DISTINCT FROM OLD.[[UserTotp.Tag]] OR NEW.[[UserTotp.KekId]] IS DISTINCT FROM OLD.[[UserTotp.KekId]] THEN
        IF NOT EXISTS (
            SELECT 1 FROM information_schema.table_privileges p
            WHERE p.table_schema = 'public' AND p.table_name = '[[UserTotp.Table]]' AND p.privilege_type = 'TRIGGER'
              AND p.grantor = p.grantee AND CASE WHEN p.grantor = p.grantee THEN pg_has_role(current_user, p.grantee::name, 'USAGE') ELSE false END
        ) THEN
            RAISE EXCEPTION 'TOTP secret material is changed only by the table owner (or a member of it), never by the runtime account';
        END IF;
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER {{TotpGuard.TrOwnerOnly}} BEFORE UPDATE ON [[UserTotp.Table]] FOR EACH ROW EXECUTE FUNCTION {{TotpGuard.FnOwnerOnly}}();
`;
function prefixOf(token) {
  const last = token.split(".").pop();
  if (!token.includes(".")) return "t_";
  if (/^Fn[A-Z]/.test(last)) return "f_";
  if (/^Tr[A-Z]/.test(last)) return "r_";
  if (/^(Pk|Uq|Fk|Ck|Ix)([A-Z]|$)/.test(last)) return "k_";
  return "c_";
}
const physical = (token) => prefixOf(token) + crypto.createHash("sha256").update("hasm.system.totp-owner-only.v1:" + token).digest("hex").slice(0, 8);

function existingNames() {
  const names = new Set();
  const scan = (dir) => {
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
      const p = path.join(dir, e.name);
      if (e.isDirectory()) { if (e.name !== "bin" && e.name !== "obj") scan(p); continue; }
      if (p === outSql || p === outCs) continue;
      if (!/\.(sql|cs)$/.test(e.name)) continue;
      for (const m of fs.readFileSync(p, "utf8").matchAll(/\b[tcfkr]_[0-9a-f]{8}\b/g)) names.add(m[0]);
    }
  };
  scan(path.join(infra, "CompanyDatabase")); scan(path.join(infra, "SystemDatabase"));
  return names;
}

function generate() {
  const body = TEMPLATE.replace(/\[\[([A-Za-z0-9.]+)\]\]/g, (_, k) => ext(k));
  const tokens = [...new Set([...body.matchAll(/\{\{([A-Za-z0-9.]+)\}\}/g)].map((m) => m[1]))];
  const taken = existingNames();
  const byToken = new Map(), seen = new Map();
  for (const t of tokens) {
    const name = physical(t);
    if (taken.has(name)) throw new Error(`collision with an existing name: ${t} -> ${name}`);
    if (seen.has(name)) throw new Error(`collision inside the migration: ${t} and ${seen.get(name)} -> ${name}`);
    seen.set(name, t); byToken.set(t, name);
  }
  const sql = body.replace(/\{\{([A-Za-z0-9.]+)\}\}/g, (_, t) => byToken.get(t));
  const entities = [...new Set(tokens.map((t) => t.split(".")[0]))];
  let cs = "namespace Hasm.Infrastructure.SystemDatabase;\n\n// GENERATED by tools/schema/system-totp-owner-only.cjs for the system migration of the second part of owner decision D-235 (owner-only guard on the TOTP secret material). Do not edit: re-run the generator.\n" +
    "// Physical names are opaque (D-029), derived deterministically from the logical token (the seed does not contain the migration number), and fixed: changing one requires a new migration.\n" +
    "// TotpGuard names the one trigger function and the one trigger of that migration (no table).\npublic static partial class SystemSchema\n{\n";
  for (const e of entities) {
    cs += `    public static class ${e}\n    {\n`;
    if (byToken.has(e)) cs += `        public const string Table = "${byToken.get(e)}";\n`;
    for (const t of tokens.filter((x) => x.startsWith(e + "."))) cs += `        public const string ${t.slice(e.length + 1)} = "${byToken.get(t)}";\n`;
    cs += "    }\n\n";
  }
  cs += "    private static IReadOnlyDictionary<string, string> TotpGuardMap { get; } = new Dictionary<string, string>\n    {\n";
  for (const t of tokens) cs += `        ["${t.includes(".") ? t : t + ".Table"}"] = ${t.includes(".") ? t : t + ".Table"},\n`;
  cs += "    };\n}\n";
  return { sql, cs };
}

const { sql, cs } = generate();
const mode = process.argv[2];
if (mode === "--write") { fs.writeFileSync(outSql, sql); fs.writeFileSync(outCs, cs); console.log("written"); }
else if (mode === "--check") {
  const norm = (s) => s.replace(/\r\n/g, "\n");
  const ok = fs.existsSync(outSql) && fs.existsSync(outCs) && norm(fs.readFileSync(outSql, "utf8")) === sql && norm(fs.readFileSync(outCs, "utf8")) === cs;
  if (!ok) { console.error("generated TOTP owner-only schema differs from the committed files"); process.exit(1); }
  console.log("TOTP owner-only schema files match the generator");
} else { console.error("usage: --write | --check"); process.exit(2); }
