#!/usr/bin/env node
// Deterministic generator for the SYSTEM migration of identity integrity slice S-1 (docs/IDENTITY-INTEGRITY-PLAN.md, register item SEC-RT-SESSION): the integrity columns of the session table and the security revision of the user table.
// SINGLE SOURCE: the SQL template below, written with LOGICAL tokens such as {{SessionIntegrity.Tag}}. Every opaque physical name (D-029) is derived as
//   prefix + first 8 hex digits of SHA-256("hasm.system.identity-integrity.v1:" + token)
// The seed deliberately does NOT contain the migration number: the number is assigned when the slice merges (the next free system number), so the names never change when the file is renumbered.
// References to names that already exist (the session and user tables, written [[Session.Table]] and [[User.Table]]) are written [[Entity.Name]] and resolved from the committed system dictionaries, never re-derived.
// Usage:  node tools/schema/system-identity-integrity.cjs --write | --check
// RENUMBERING at merge: change MIGRATION_FILE below, re-run --write, and update the pinned migration counts in the tests (the journal count assertions).
const fs = require("fs");
const path = require("path");
const crypto = require("crypto");

const MIGRATION_FILE = "0036_session_tags_and_security_revision.sql";   // PROVISIONAL number: renamed at merge time (see above)
const root = path.resolve(__dirname, "..", "..");
const infra = path.join(root, "src", "backend", "Hasm.Infrastructure");
const outSql = path.join(infra, "SystemDatabase", "Migrations", MIGRATION_FILE);
const outCs = path.join(infra, "SystemDatabase", "SystemSchema.IdentityIntegrity.cs");

function parseDictionary(file) {
  const text = fs.readFileSync(path.join(infra, "SystemDatabase", file), "utf8");
  const map = new Map();
  for (const m of text.matchAll(/public static class (\w+)\s*\{([\s\S]*?)\n    \}/g))
    for (const c of m[2].matchAll(/public const string (\w+) = "([tcfkr]_[0-9a-f]{8})";/g)) map.set(`${m[1]}.${c[1]}`, c[2]);
  return map;
}
const EXISTING = new Map([...parseDictionary("SystemSchema.cs")]);
const ext = (key) => { const v = EXISTING.get(key); if (!v) throw new Error("unknown existing name " + key); return v; };

const TEMPLATE = `-- Migration (system): identity integrity slice S-1 (docs/IDENTITY-INTEGRITY-PLAN.md, register item SEC-RT-SESSION; owner decisions OD-1 and OD-2). Forward-only and ADDITIVE: three NULLable columns and one check on the
-- session table, one security-revision column with a check and one guard trigger on the user table. Nothing existing is dropped, replaced, disabled or modified, nothing is seeded, no catalog table is written and no
-- setting is touched. Opaque physical names (D-029) are generated by tools/schema/system-identity-integrity.cjs (logical dictionary: SystemSchema.IdentityIntegrity.cs). Do not edit by hand: re-run the generator.
--
-- WHAT THIS IS: a session row is authenticated by the API with keys the database does not hold (the keyed token hash and a MAC over the security fields of the row, key id and tag stored here); a row without a valid
-- tag is not a session. UserRevisionAtIssue is the security revision of the user at the time the session was issued: a session is valid only while it equals the user's current revision, which password change and
-- revoke-all raise. Existing session rows carry no tag and stop matching at rollout (every user signs in again; there is no compatibility mode, owner decision OD-2). The database cannot verify a MAC (it has no key);
-- what needs no key it enforces: the shape of the three columns, and that a user's security revision stays or grows by exactly one per update (never decreases, never jumps, so the application bump can never overflow).

ALTER TABLE [[Session.Table]]
    ADD COLUMN {{SessionIntegrity.KeyId}} varchar(32) NULL,
    ADD COLUMN {{SessionIntegrity.Tag}} bytea NULL,
    ADD COLUMN {{SessionIntegrity.UserRevisionAtIssue}} bigint NULL,
    ADD CONSTRAINT {{SessionIntegrity.CkIntegrity}} CHECK (({{SessionIntegrity.KeyId}} IS NULL AND {{SessionIntegrity.Tag}} IS NULL AND {{SessionIntegrity.UserRevisionAtIssue}} IS NULL)
        OR ({{SessionIntegrity.KeyId}} ~ '^[a-z0-9][a-z0-9-]{0,31}$' AND octet_length({{SessionIntegrity.Tag}}) = 32 AND {{SessionIntegrity.UserRevisionAtIssue}} >= 0));

ALTER TABLE [[User.Table]]
    ADD COLUMN {{UserIntegrity.SecurityRevision}} bigint NOT NULL DEFAULT 0,
    ADD CONSTRAINT {{UserIntegrity.CkRevision}} CHECK ({{UserIntegrity.SecurityRevision}} >= 0 AND {{UserIntegrity.SecurityRevision}} < 4611686018427387904);

CREATE FUNCTION {{UserIntegrity.FnRevisionGuard}}() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.{{UserIntegrity.SecurityRevision}} <> OLD.{{UserIntegrity.SecurityRevision}} AND NEW.{{UserIntegrity.SecurityRevision}} <> OLD.{{UserIntegrity.SecurityRevision}} + 1 THEN
        RAISE EXCEPTION 'the security revision of a user only stays or grows by exactly one';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER {{UserIntegrity.TrRevisionGuard}} BEFORE UPDATE ON [[User.Table]] FOR EACH ROW EXECUTE FUNCTION {{UserIntegrity.FnRevisionGuard}}();
`;
function prefixOf(token) {
  const last = token.split(".").pop();
  if (!token.includes(".")) return "t_";
  if (/^Fn[A-Z]/.test(last)) return "f_";
  if (/^Tr[A-Z]/.test(last)) return "r_";
  if (/^(Pk|Uq|Fk|Ck|Ix)([A-Z]|$)/.test(last)) return "k_";
  return "c_";
}
const physical = (token) => prefixOf(token) + crypto.createHash("sha256").update("hasm.system.identity-integrity.v1:" + token).digest("hex").slice(0, 8);

function existingNames() {
  const names = new Set();
  const scan = (dir) => {
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
      const p = path.join(dir, e.name);
      if (e.isDirectory()) { if (e.name !== "bin" && e.name !== "obj") scan(p); continue; }
      if (p === outSql || p === outCs) continue;
      if (!/\.(sql|cs)$/.test(e.name)) continue;
      for (const m of fs.readFileSync(p, "utf8").matchAll(/\b[tcfkr]_[0-9a-f]{8}\b/g)) names.add(m[0]);
    }
  };
  scan(path.join(infra, "CompanyDatabase")); scan(path.join(infra, "SystemDatabase"));
  return names;
}

function generate() {
  const body = TEMPLATE.replace(/\[\[([A-Za-z0-9.]+)\]\]/g, (_, k) => ext(k));
  const tokens = [...new Set([...body.matchAll(/\{\{([A-Za-z0-9.]+)\}\}/g)].map((m) => m[1]))];
  const taken = existingNames();
  const byToken = new Map(), seen = new Map();
  for (const t of tokens) {
    const name = physical(t);
    if (taken.has(name)) throw new Error(`collision with an existing name: ${t} -> ${name}`);
    if (seen.has(name)) throw new Error(`collision inside the migration: ${t} and ${seen.get(name)} -> ${name}`);
    seen.set(name, t); byToken.set(t, name);
  }
  const sql = body.replace(/\{\{([A-Za-z0-9.]+)\}\}/g, (_, t) => byToken.get(t));
  const entities = [...new Set(tokens.map((t) => t.split(".")[0]))];
  let cs = "namespace Hasm.Infrastructure.SystemDatabase;\n\n// GENERATED by tools/schema/system-identity-integrity.cjs for the system migration of the identity integrity slice S-1. Do not edit: re-run the generator.\n" +
    "// Physical names are opaque (D-029), derived deterministically from the logical token (the seed does not contain the migration number), and fixed: changing one requires a new migration.\n" +
    "// SessionIntegrity and UserIntegrity name the columns, the check, the function and the trigger of identity integrity slice S-1 (no table).\npublic static partial class SystemSchema\n{\n";
  for (const e of entities) {
    cs += `    public static class ${e}\n    {\n`;
    if (byToken.has(e)) cs += `        public const string Table = "${byToken.get(e)}";\n`;
    for (const t of tokens.filter((x) => x.startsWith(e + "."))) cs += `        public const string ${t.slice(e.length + 1)} = "${byToken.get(t)}";\n`;
    cs += "    }\n\n";
  }
  cs += "    private static IReadOnlyDictionary<string, string> IdentityIntegrityMap { get; } = new Dictionary<string, string>\n    {\n";
  for (const t of tokens) cs += `        ["${t.includes(".") ? t : t + ".Table"}"] = ${t.includes(".") ? t : t + ".Table"},\n`;
  cs += "    };\n}\n";
  return { sql, cs };
}

const { sql, cs } = generate();
const mode = process.argv[2];
if (mode === "--write") { fs.writeFileSync(outSql, sql); fs.writeFileSync(outCs, cs); console.log("written"); }
else if (mode === "--check") {
  const norm = (s) => s.replace(/\r\n/g, "\n");
  const ok = fs.existsSync(outSql) && fs.existsSync(outCs) && norm(fs.readFileSync(outSql, "utf8")) === sql && norm(fs.readFileSync(outCs, "utf8")) === cs;
  if (!ok) { console.error("generated identity integrity schema differs from the committed files"); process.exit(1); }
  console.log("identity integrity schema files match the generator");
} else { console.error("usage: --write | --check"); process.exit(2); }
