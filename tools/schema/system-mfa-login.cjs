#!/usr/bin/env node
// Deterministic generator for the SYSTEM migration of Phase 4.1 slice S2 (MFA login challenges and session MFA state).
// SINGLE SOURCE: the SQL template below, written with LOGICAL tokens such as {{MfaChallenge.TokenHash}}. Every opaque physical name (D-029) is derived as
//   prefix + first 8 hex digits of SHA-256("hasm.system.mfa-login.v1:" + token)
// The seed deliberately does NOT contain the migration number: the number is assigned when the slice merges (the next free system number), so the names never change when the file is renumbered.
// (same prefix rules as tools/schema/company-0030-document-links.cjs: a collision aborts the run; names are fixed once committed). References to names that already exist are written [[Entity.Name]]
// and resolved from the committed system dictionaries, never re-derived.
// Usage:  node tools/schema/system-mfa-login.cjs --write | --check
// RENUMBERING at merge: change MIGRATION_FILE below, re-run --write, and update the pinned migration counts in the tests (the journal count assertions).
const fs = require("fs");
const path = require("path");
const crypto = require("crypto");

const MIGRATION_FILE = "0033_mfa_login_challenges.sql";   // PROVISIONAL number: renamed at merge time (see above)
const root = path.resolve(__dirname, "..", "..");
const infra = path.join(root, "src", "backend", "Hasm.Infrastructure");
const outSql = path.join(infra, "SystemDatabase", "Migrations", MIGRATION_FILE);
const outCs = path.join(infra, "SystemDatabase", "SystemSchema.MfaLogin.cs");

function parseDictionary(file) {
  const text = fs.readFileSync(path.join(infra, "SystemDatabase", file), "utf8");
  const map = new Map();
  for (const m of text.matchAll(/public static class (\w+)\s*\{([\s\S]*?)\n    \}/g))
    for (const c of m[2].matchAll(/public const string (\w+) = "([tcfkr]_[0-9a-f]{8})";/g)) map.set(`${m[1]}.${c[1]}`, c[2]);
  return map;
}
const EXISTING = new Map([...parseDictionary("SystemSchema.cs"), ...parseDictionary("SystemSchema.Parties.cs")]);
const ext = (key) => { const v = EXISTING.get(key); if (!v) throw new Error("unknown existing name " + key); return v; };

const TEMPLATE = `-- Migration (system): MFA login challenges and session MFA state (Phase 4.1 slice S2, docs/PHASE-4.1.md section 5, decisions D-080, D-121). Forward-only, additive: three columns and one check on the session table and ONE new table;
-- nothing existing is dropped or replaced. Opaque physical names (D-029) are generated by tools/schema/system-mfa-login.cjs (logical dictionary: SystemSchema.MfaLogin.cs). Do not edit by hand: re-run the generator.
--
-- WHAT THIS IS: a login with a required second factor creates NO session after the password step: it creates a short-lived, single-purpose CHALLENGE (only the SHA-256 of its 256-bit token is stored), bound to the user, the
-- client kind and the source address, with a small attempt budget. The session is created only after the second factor succeeded and records how: auth_methods is a bitmask (1 password, 2 totp); a session that has the totp bit
-- must carry the time of the verification. purpose: 0 login, 1 enrol, 2 recovery request.

ALTER TABLE [[Session.Table]]
    ADD COLUMN {{SessionMfa.VerifiedAtUtc}} timestamptz NULL,
    ADD COLUMN {{SessionMfa.AuthMethods}} smallint NOT NULL DEFAULT 1,
    ADD COLUMN {{SessionMfa.Emergency}} boolean NOT NULL DEFAULT false;
ALTER TABLE [[Session.Table]] ADD CONSTRAINT {{SessionMfa.CkAuthMethods}} CHECK ({{SessionMfa.AuthMethods}} BETWEEN 1 AND 3 AND ({{SessionMfa.AuthMethods}} & 2 = 0 OR {{SessionMfa.VerifiedAtUtc}} IS NOT NULL));

CREATE TABLE {{MfaChallenge}} (
    {{MfaChallenge.Id}} uuid NOT NULL,
    {{MfaChallenge.UserId}} uuid NOT NULL,
    {{MfaChallenge.TokenHash}} bytea NOT NULL,
    {{MfaChallenge.Purpose}} smallint NOT NULL,
    {{MfaChallenge.ClientKind}} smallint NOT NULL,
    {{MfaChallenge.SourceHash}} bytea NOT NULL,
    {{MfaChallenge.CreatedAtUtc}} timestamptz NOT NULL,
    {{MfaChallenge.ExpiresAtUtc}} timestamptz NOT NULL,
    {{MfaChallenge.Attempts}} integer NOT NULL DEFAULT 0,
    {{MfaChallenge.ConsumedAtUtc}} timestamptz NULL,
    CONSTRAINT {{MfaChallenge.Pk}} PRIMARY KEY ({{MfaChallenge.Id}}),
    CONSTRAINT {{MfaChallenge.FkUser}} FOREIGN KEY ({{MfaChallenge.UserId}}) REFERENCES [[User.Table]] ([[User.Id]]),
    CONSTRAINT {{MfaChallenge.UqTokenHash}} UNIQUE ({{MfaChallenge.TokenHash}}),
    CONSTRAINT {{MfaChallenge.CkValues}} CHECK (octet_length({{MfaChallenge.TokenHash}}) = 32 AND octet_length({{MfaChallenge.SourceHash}}) = 32 AND {{MfaChallenge.Purpose}} IN (0, 1, 2)
        AND {{MfaChallenge.ClientKind}} IN (0, 1) AND {{MfaChallenge.Attempts}} >= 0 AND {{MfaChallenge.ExpiresAtUtc}} > {{MfaChallenge.CreatedAtUtc}})
);
CREATE INDEX {{MfaChallenge.IxUser}} ON {{MfaChallenge}} ({{MfaChallenge.UserId}}, {{MfaChallenge.ExpiresAtUtc}});

-- a challenge never changes who or what it is for, is consumed at most once, and its attempt counter only grows
CREATE FUNCTION {{MfaChallenge.FnGuard}}() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
    IF NEW.{{MfaChallenge.Id}} IS DISTINCT FROM OLD.{{MfaChallenge.Id}} OR NEW.{{MfaChallenge.UserId}} IS DISTINCT FROM OLD.{{MfaChallenge.UserId}} OR NEW.{{MfaChallenge.TokenHash}} IS DISTINCT FROM OLD.{{MfaChallenge.TokenHash}}
       OR NEW.{{MfaChallenge.Purpose}} IS DISTINCT FROM OLD.{{MfaChallenge.Purpose}} OR NEW.{{MfaChallenge.ClientKind}} IS DISTINCT FROM OLD.{{MfaChallenge.ClientKind}}
       OR NEW.{{MfaChallenge.SourceHash}} IS DISTINCT FROM OLD.{{MfaChallenge.SourceHash}} OR NEW.{{MfaChallenge.CreatedAtUtc}} IS DISTINCT FROM OLD.{{MfaChallenge.CreatedAtUtc}}
       OR NEW.{{MfaChallenge.ExpiresAtUtc}} IS DISTINCT FROM OLD.{{MfaChallenge.ExpiresAtUtc}} THEN
        RAISE EXCEPTION 'the identity of a challenge is immutable';
    END IF;
    IF OLD.{{MfaChallenge.ConsumedAtUtc}} IS NOT NULL AND NEW.{{MfaChallenge.ConsumedAtUtc}} IS DISTINCT FROM OLD.{{MfaChallenge.ConsumedAtUtc}} THEN RAISE EXCEPTION 'a challenge is consumed at most once'; END IF;
    IF NEW.{{MfaChallenge.Attempts}} < OLD.{{MfaChallenge.Attempts}} THEN RAISE EXCEPTION 'the attempt counter of a challenge never decreases'; END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER {{MfaChallenge.TrRow}} BEFORE UPDATE OR DELETE ON {{MfaChallenge}} FOR EACH ROW EXECUTE FUNCTION {{MfaChallenge.FnGuard}}();
REVOKE ALL ON TABLE {{MfaChallenge}} FROM PUBLIC;
`;

function prefixOf(token) {
  const last = token.split(".").pop();
  if (!token.includes(".")) return "t_";
  if (/^Fn[A-Z]/.test(last)) return "f_";
  if (/^Tr[A-Z]/.test(last)) return "r_";
  if (/^(Pk|Uq|Fk|Ck|Ix)([A-Z]|$)/.test(last)) return "k_";
  return "c_";
}
const physical = (token) => prefixOf(token) + crypto.createHash("sha256").update("hasm.system.mfa-login.v1:" + token).digest("hex").slice(0, 8);

function existingNames() {
  const names = new Set();
  const scan = (dir) => {
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
      const p = path.join(dir, e.name);
      if (e.isDirectory()) { if (e.name !== "bin" && e.name !== "obj") scan(p); continue; }
      if (p === outSql || p === outCs || p.endsWith("0039_mfa_challenge_tag.sql") || p.endsWith("SystemSchema.ChallengeTag.cs")) continue;   // the later slice that only ADDS columns to this table (it repeats the table name by reference)
      if (!/\.(sql|cs)$/.test(e.name)) continue;
      for (const m of fs.readFileSync(p, "utf8").matchAll(/\b[tcfkr]_[0-9a-f]{8}\b/g)) names.add(m[0]);
    }
  };
  scan(path.join(infra, "CompanyDatabase")); scan(path.join(infra, "SystemDatabase"));
  return names;
}

function generate() {
  const body = TEMPLATE.replace(/\[\[([A-Za-z0-9.]+)\]\]/g, (_, k) => ext(k));
  const tokens = [...new Set([...body.matchAll(/\{\{([A-Za-z0-9.]+)\}\}/g)].map((m) => m[1]))];
  const taken = existingNames();
  const byToken = new Map(), seen = new Map();
  for (const t of tokens) {
    const name = physical(t);
    if (taken.has(name)) throw new Error(`collision with an existing name: ${t} -> ${name}`);
    if (seen.has(name)) throw new Error(`collision inside the migration: ${t} and ${seen.get(name)} -> ${name}`);
    seen.set(name, t); byToken.set(t, name);
  }
  const sql = body.replace(/\{\{([A-Za-z0-9.]+)\}\}/g, (_, t) => byToken.get(t));
  const entities = [...new Set(tokens.map((t) => t.split(".")[0]))];
  let cs = "namespace Hasm.Infrastructure.SystemDatabase;\n\n// GENERATED by tools/schema/system-mfa.cjs for the system migration of Phase 4.1 slice S2 (MFA login challenges and session MFA state). Do not edit: re-run the generator.\n" +
    "// Physical names are opaque (D-029), derived deterministically from the logical token (the seed does not contain the migration number), and fixed: changing one requires a new migration.\n" +
    "// SessionMfa holds the columns and the check ADDED to the session table; MfaChallenge is the new ephemeral secret-store table.\npublic static partial class SystemSchema\n{\n";
  for (const e of entities) {
    cs += `    public static class ${e}\n    {\n`;
    if (byToken.has(e)) cs += `        public const string Table = "${byToken.get(e)}";\n`;
    for (const t of tokens.filter((x) => x.startsWith(e + "."))) cs += `        public const string ${t.slice(e.length + 1)} = "${byToken.get(t)}";\n`;
    cs += "    }\n\n";
  }
  cs += "    private static IReadOnlyDictionary<string, string> MfaLoginMap { get; } = new Dictionary<string, string>\n    {\n";
  for (const t of tokens) cs += `        ["${t.includes(".") ? t : t + ".Table"}"] = ${t.includes(".") ? t : t + ".Table"},\n`;   // the system dictionary names a table "Entity.Table"
  cs += "    };\n}\n";
  return { sql, cs };
}

const { sql, cs } = generate();
const mode = process.argv[2];
if (mode === "--write") { fs.writeFileSync(outSql, sql); fs.writeFileSync(outCs, cs); console.log("written"); }
else if (mode === "--check") {
  const norm = (s) => s.replace(/\r\n/g, "\n");
  const ok = fs.existsSync(outSql) && fs.existsSync(outCs) && norm(fs.readFileSync(outSql, "utf8")) === sql && norm(fs.readFileSync(outCs, "utf8")) === cs;
  if (!ok) { console.error("generated MFA login schema differs from the committed files"); process.exit(1); }
  console.log("MFA login schema files match the generator");
} else { console.error("usage: --write | --check"); process.exit(2); }
