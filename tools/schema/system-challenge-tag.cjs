#!/usr/bin/env node
// Deterministic generator for the SYSTEM migration of identity integrity slice S-2d (docs/IDENTITY-INTEGRITY-PLAN.md, register item SEC-RT-SESSION): the integrity columns (key id and tag) of the second-factor challenge table.
// SINGLE SOURCE: the SQL template below, written with LOGICAL tokens such as {{SessionIntegrity.Tag}}. Every opaque physical name (D-029) is derived as
//   prefix + first 8 hex digits of SHA-256("hasm.system.challenge-tag.v1:" + token)
// The seed deliberately does NOT contain the migration number: the number is assigned when the slice merges (the next free system number), so the names never change when the file is renumbered.
// References to names that already exist (the session and user tables, written [[MfaChallenge.Table]]) are written [[Entity.Name]] and resolved from the committed system dictionaries, never re-derived.
// Usage:  node tools/schema/system-challenge-tag.cjs --write | --check
// RENUMBERING at merge: change MIGRATION_FILE below, re-run --write, and update the pinned migration counts in the tests (the journal count assertions).
const fs = require("fs");
const path = require("path");
const crypto = require("crypto");

const MIGRATION_FILE = "0039_mfa_challenge_tag.sql";   // PROVISIONAL number: renamed at merge time (see above)
const root = path.resolve(__dirname, "..", "..");
const infra = path.join(root, "src", "backend", "Hasm.Infrastructure");
const outSql = path.join(infra, "SystemDatabase", "Migrations", MIGRATION_FILE);
const outCs = path.join(infra, "SystemDatabase", "SystemSchema.ChallengeTag.cs");

function parseDictionary(file) {
  const text = fs.readFileSync(path.join(infra, "SystemDatabase", file), "utf8");
  const map = new Map();
  for (const m of text.matchAll(/public static class (\w+)\s*\{([\s\S]*?)\n    \}/g))
    for (const c of m[2].matchAll(/public const string (\w+) = "([tcfkr]_[0-9a-f]{8})";/g)) map.set(`${m[1]}.${c[1]}`, c[2]);
  return map;
}
const EXISTING = new Map([...parseDictionary("SystemSchema.cs"), ...parseDictionary("SystemSchema.MfaLogin.cs")]);
const ext = (key) => { const v = EXISTING.get(key); if (!v) throw new Error("unknown existing name " + key); return v; };

const TEMPLATE = `-- Migration (system): identity integrity slice S-2d (docs/IDENTITY-INTEGRITY-PLAN.md section 5.1; owner decisions OD-1 and OD-2). Forward-only and ADDITIVE: two NULLable columns and one check, and one BEFORE DELETE guard, on the second-factor challenge
-- table. Nothing existing is dropped, replaced, disabled or modified, nothing is seeded and no setting is touched. Opaque physical names (D-029) are generated by tools/schema/system-challenge-tag.cjs (logical dictionary:
-- SystemSchema.ChallengeTag.cs). Do not edit by hand: re-run the generator.
--
-- WHAT THIS IS: a challenge row carries a key id and a MAC (the tag) over its identity, purpose, client, source, times and keyed token hash, computed by the API with a key the database does not hold. A challenge without a valid
-- tag is refused like an unknown token, so a row written with the runtime credentials opens nothing. Existing challenge rows carry no tag; they live five minutes and are simply never honoured. The database cannot verify a MAC;
-- it enforces only the shape of the two columns.

ALTER TABLE [[MfaChallenge.Table]]
    ADD COLUMN {{ChallengeTag.KeyId}} varchar(32) NULL,
    ADD COLUMN {{ChallengeTag.Tag}} bytea NULL,
    ADD CONSTRAINT {{ChallengeTag.CkTag}} CHECK (({{ChallengeTag.KeyId}} IS NULL AND {{ChallengeTag.Tag}} IS NULL)
        OR ({{ChallengeTag.KeyId}} ~ '^[a-z0-9][a-z0-9-]{0,31}$' AND octet_length({{ChallengeTag.Tag}}) = 32));

-- A challenge that has not expired is never deleted (review M1 of PR 237): the tag does not cover the attempt counter or the consumption time, so a runtime-credential holder who could DELETE and re-INSERT a genuine tagged
-- row would reset its budget and undo its single use. The housekeeping purge deletes only expired rows (at least a day after expiry), and a re-inserted EXPIRED row gains nothing because the expiry is covered by the tag.
-- A separate trigger: the guard of migration 0033 is not replaced.
CREATE FUNCTION {{ChallengeTag.FnDeleteGuard}}() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF OLD.[[MfaChallenge.ExpiresAtUtc]] >= clock_timestamp() THEN
        RAISE EXCEPTION 'a challenge that has not expired is never deleted';
    END IF;
    RETURN OLD;
END;
$$;
CREATE TRIGGER {{ChallengeTag.TrDeleteGuard}} BEFORE DELETE ON [[MfaChallenge.Table]] FOR EACH ROW EXECUTE FUNCTION {{ChallengeTag.FnDeleteGuard}}();
`;
function prefixOf(token) {
  const last = token.split(".").pop();
  if (!token.includes(".")) return "t_";
  if (/^Fn[A-Z]/.test(last)) return "f_";
  if (/^Tr[A-Z]/.test(last)) return "r_";
  if (/^(Pk|Uq|Fk|Ck|Ix)([A-Z]|$)/.test(last)) return "k_";
  return "c_";
}
const physical = (token) => prefixOf(token) + crypto.createHash("sha256").update("hasm.system.challenge-tag.v1:" + token).digest("hex").slice(0, 8);

function existingNames() {
  const names = new Set();
  const scan = (dir) => {
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
      const p = path.join(dir, e.name);
      if (e.isDirectory()) { if (e.name !== "bin" && e.name !== "obj") scan(p); continue; }
      if (p === outSql || p === outCs) continue;
      if (!/\.(sql|cs)$/.test(e.name)) continue;
      for (const m of fs.readFileSync(p, "utf8").matchAll(/\b[tcfkr]_[0-9a-f]{8}\b/g)) names.add(m[0]);
    }
  };
  scan(path.join(infra, "CompanyDatabase")); scan(path.join(infra, "SystemDatabase"));
  return names;
}

function generate() {
  const body = TEMPLATE.replace(/\[\[([A-Za-z0-9.]+)\]\]/g, (_, k) => ext(k));
  const tokens = [...new Set([...body.matchAll(/\{\{([A-Za-z0-9.]+)\}\}/g)].map((m) => m[1]))];
  const taken = existingNames();
  const byToken = new Map(), seen = new Map();
  for (const t of tokens) {
    const name = physical(t);
    if (taken.has(name)) throw new Error(`collision with an existing name: ${t} -> ${name}`);
    if (seen.has(name)) throw new Error(`collision inside the migration: ${t} and ${seen.get(name)} -> ${name}`);
    seen.set(name, t); byToken.set(t, name);
  }
  const sql = body.replace(/\{\{([A-Za-z0-9.]+)\}\}/g, (_, t) => byToken.get(t));
  const entities = [...new Set(tokens.map((t) => t.split(".")[0]))];
  let cs = "namespace Hasm.Infrastructure.SystemDatabase;\n\n// GENERATED by tools/schema/system-identity-integrity.cjs for the system migration of the identity integrity slice S-2d. Do not edit: re-run the generator.\n" +
    "// Physical names are opaque (D-029), derived deterministically from the logical token (the seed does not contain the migration number), and fixed: changing one requires a new migration.\n" +
    "// ChallengeTag names the two columns and the check of identity integrity slice S-2d (no table).\npublic static partial class SystemSchema\n{\n";
  for (const e of entities) {
    cs += `    public static class ${e}\n    {\n`;
    if (byToken.has(e)) cs += `        public const string Table = "${byToken.get(e)}";\n`;
    for (const t of tokens.filter((x) => x.startsWith(e + "."))) cs += `        public const string ${t.slice(e.length + 1)} = "${byToken.get(t)}";\n`;
    cs += "    }\n\n";
  }
  cs += "    private static IReadOnlyDictionary<string, string> ChallengeTagMap { get; } = new Dictionary<string, string>\n    {\n";
  for (const t of tokens) cs += `        ["${t.includes(".") ? t : t + ".Table"}"] = ${t.includes(".") ? t : t + ".Table"},\n`;
  cs += "    };\n}\n";
  return { sql, cs };
}

const { sql, cs } = generate();
const mode = process.argv[2];
if (mode === "--write") { fs.writeFileSync(outSql, sql); fs.writeFileSync(outCs, cs); console.log("written"); }
else if (mode === "--check") {
  const norm = (s) => s.replace(/\r\n/g, "\n");
  const ok = fs.existsSync(outSql) && fs.existsSync(outCs) && norm(fs.readFileSync(outSql, "utf8")) === sql && norm(fs.readFileSync(outCs, "utf8")) === cs;
  if (!ok) { console.error("generated challenge tag schema differs from the committed files"); process.exit(1); }
  console.log("challenge tag schema files match the generator");
} else { console.error("usage: --write | --check"); process.exit(2); }
