#!/usr/bin/env node
// Deterministic generator for the SYSTEM migration of Phase 4.1 slice S3b-1b (company MFA policy).
// SINGLE SOURCE: the SQL template below, written with LOGICAL tokens such as {{MfaPolicy.Policy}}. Every opaque physical name (D-029) is derived as
//   prefix + first 8 hex digits of SHA-256("hasm.system.mfa-policy.v1:" + token)
// The seed deliberately does NOT contain the migration number: the number is assigned when the slice merges (the next free system number), so the names never change when the file is renumbered.
// (same prefix rules as tools/schema/company-0030-document-links.cjs: a collision aborts the run; names are fixed once committed). References to names that already exist are written [[Entity.Name]]
// and resolved from the committed system dictionaries, never re-derived.
// Usage:  node tools/schema/system-mfa-policy.cjs --write | --check
// RENUMBERING at merge: change MIGRATION_FILE below, re-run --write, and update the pinned migration counts in the tests (the journal count assertions).
const fs = require("fs");
const path = require("path");
const crypto = require("crypto");

const MIGRATION_FILE = "0034_company_mfa_policy.sql";   // PROVISIONAL number: renamed at merge time (see above)
const root = path.resolve(__dirname, "..", "..");
const infra = path.join(root, "src", "backend", "Hasm.Infrastructure");
const outSql = path.join(infra, "SystemDatabase", "Migrations", MIGRATION_FILE);
const outCs = path.join(infra, "SystemDatabase", "SystemSchema.MfaPolicy.cs");

function parseDictionary(file) {
  const text = fs.readFileSync(path.join(infra, "SystemDatabase", file), "utf8");
  const map = new Map();
  for (const m of text.matchAll(/public static class (\w+)\s*\{([\s\S]*?)\n    \}/g))
    for (const c of m[2].matchAll(/public const string (\w+) = "([tcfkr]_[0-9a-f]{8})";/g)) map.set(`${m[1]}.${c[1]}`, c[2]);
  return map;
}
const EXISTING = new Map([...parseDictionary("SystemSchema.cs"), ...parseDictionary("SystemSchema.Parties.cs")]);
const ext = (key) => { const v = EXISTING.get(key); if (!v) throw new Error("unknown existing name " + key); return v; };

const TEMPLATE = `-- Migration (system): company MFA policy (Phase 4.1 slice S3b-1b, docs/PHASE-4.1.md section 3, decisions D-080, D-167). Forward-only, additive: two tables and rows added to the preset Company Administrator role;
-- nothing existing is dropped or replaced. Opaque physical names (D-029) are generated by tools/schema/system-mfa-policy.cjs (logical dictionary: SystemSchema.MfaPolicy.cs). Do not edit by hand: re-run the generator.
--
-- WHAT THIS IS: the per-company setting MfaPolicy = Off | RequiredForRoles(list) | RequiredForAll. A company with no row has policy Off. The policy is NOT a secret: it is part of the system dump and of every backup.
-- policy: 0 Off, 1 RequiredForRoles, 2 RequiredForAll. The list of roles of a RequiredForRoles policy is {{MfaPolicyRole}}; the service keeps it empty for the other two kinds.

CREATE TABLE {{MfaPolicy}} (
    {{MfaPolicy.CompanyId}} uuid NOT NULL,
    {{MfaPolicy.Policy}} smallint NOT NULL,
    {{MfaPolicy.UpdatedAtUtc}} timestamptz NOT NULL,
    {{MfaPolicy.UpdatedBy}} uuid NOT NULL,
    CONSTRAINT {{MfaPolicy.Pk}} PRIMARY KEY ({{MfaPolicy.CompanyId}}),
    CONSTRAINT {{MfaPolicy.FkCompany}} FOREIGN KEY ({{MfaPolicy.CompanyId}}) REFERENCES [[Company.Table]] ([[Company.Id]]),
    CONSTRAINT {{MfaPolicy.FkUpdatedBy}} FOREIGN KEY ({{MfaPolicy.UpdatedBy}}) REFERENCES [[User.Table]] ([[User.Id]]),
    CONSTRAINT {{MfaPolicy.CkPolicy}} CHECK ({{MfaPolicy.Policy}} IN (0, 1, 2))
);

CREATE TABLE {{MfaPolicyRole}} (
    {{MfaPolicyRole.CompanyId}} uuid NOT NULL,
    {{MfaPolicyRole.RoleId}} uuid NOT NULL,
    CONSTRAINT {{MfaPolicyRole.Pk}} PRIMARY KEY ({{MfaPolicyRole.CompanyId}}, {{MfaPolicyRole.RoleId}}),
    CONSTRAINT {{MfaPolicyRole.FkPolicy}} FOREIGN KEY ({{MfaPolicyRole.CompanyId}}) REFERENCES {{MfaPolicy}} ({{MfaPolicy.CompanyId}}),
    CONSTRAINT {{MfaPolicyRole.FkRole}} FOREIGN KEY ({{MfaPolicyRole.RoleId}}) REFERENCES [[Role.Table]] ([[Role.Id]])
);
CREATE INDEX {{MfaPolicyRole.IxRole}} ON {{MfaPolicyRole}} ({{MfaPolicyRole.RoleId}});

REVOKE ALL ON TABLE {{MfaPolicy}} FROM PUBLIC;
REVOKE ALL ON TABLE {{MfaPolicyRole}} FROM PUBLIC;

-- the new permission access.mfapolicy.view and access.mfapolicy.update belongs to the preset Company Administrator (the preset holds every permission except the separated approvals). Preset roles are immutable through the
-- application, so the immutability triggers are paused for exactly this versioned change, inside this transaction, and re-enabled before it ends.
ALTER TABLE [[Role.Table]] DISABLE TRIGGER [[Role.GuardTrigger]];
ALTER TABLE [[RolePermission.Table]] DISABLE TRIGGER [[RolePermission.GuardTrigger]];
INSERT INTO [[RolePermission.Table]] ([[RolePermission.RoleId]], [[RolePermission.Permission]]) VALUES
    ('5c1b0f6e-0000-4a00-8000-000000000001', 'access.mfapolicy.view'),
    ('5c1b0f6e-0000-4a00-8000-000000000001', 'access.mfapolicy.update');
ALTER TABLE [[Role.Table]] ENABLE TRIGGER [[Role.GuardTrigger]];
ALTER TABLE [[RolePermission.Table]] ENABLE TRIGGER [[RolePermission.GuardTrigger]];
`;

function prefixOf(token) {
  const last = token.split(".").pop();
  if (!token.includes(".")) return "t_";
  if (/^Fn[A-Z]/.test(last)) return "f_";
  if (/^Tr[A-Z]/.test(last)) return "r_";
  if (/^(Pk|Uq|Fk|Ck|Ix)([A-Z]|$)/.test(last)) return "k_";
  return "c_";
}
const physical = (token) => prefixOf(token) + crypto.createHash("sha256").update("hasm.system.mfa-policy.v1:" + token).digest("hex").slice(0, 8);

function existingNames() {
  const names = new Set();
  const scan = (dir) => {
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
      const p = path.join(dir, e.name);
      if (e.isDirectory()) { if (e.name !== "bin" && e.name !== "obj") scan(p); continue; }
      if (p === outSql || p === outCs) continue;
      if (!/\.(sql|cs)$/.test(e.name)) continue;
      for (const m of fs.readFileSync(p, "utf8").matchAll(/\b[tcfkr]_[0-9a-f]{8}\b/g)) names.add(m[0]);
    }
  };
  scan(path.join(infra, "CompanyDatabase")); scan(path.join(infra, "SystemDatabase"));
  return names;
}

function generate() {
  const body = TEMPLATE.replace(/\[\[([A-Za-z0-9.]+)\]\]/g, (_, k) => ext(k));
  const tokens = [...new Set([...body.matchAll(/\{\{([A-Za-z0-9.]+)\}\}/g)].map((m) => m[1]))];
  const taken = existingNames();
  const byToken = new Map(), seen = new Map();
  for (const t of tokens) {
    const name = physical(t);
    if (taken.has(name)) throw new Error(`collision with an existing name: ${t} -> ${name}`);
    if (seen.has(name)) throw new Error(`collision inside the migration: ${t} and ${seen.get(name)} -> ${name}`);
    seen.set(name, t); byToken.set(t, name);
  }
  const sql = body.replace(/\{\{([A-Za-z0-9.]+)\}\}/g, (_, t) => byToken.get(t));
  const entities = [...new Set(tokens.map((t) => t.split(".")[0]))];
  let cs = "namespace Hasm.Infrastructure.SystemDatabase;\n\n// GENERATED by tools/schema/system-mfa-policy.cjs for the system migration of Phase 4.1 slice S3b-1b (company MFA policy). Do not edit: re-run the generator.\n" +
    "// Physical names are opaque (D-029), derived deterministically from the logical token (the seed does not contain the migration number), and fixed: changing one requires a new migration.\n" +
    "// MfaPolicy and MfaPolicyRole are new, non-secret tables.\npublic static partial class SystemSchema\n{\n";
  for (const e of entities) {
    cs += `    public static class ${e}\n    {\n`;
    if (byToken.has(e)) cs += `        public const string Table = "${byToken.get(e)}";\n`;
    for (const t of tokens.filter((x) => x.startsWith(e + "."))) cs += `        public const string ${t.slice(e.length + 1)} = "${byToken.get(t)}";\n`;
    cs += "    }\n\n";
  }
  cs += "    private static IReadOnlyDictionary<string, string> MfaPolicyMap { get; } = new Dictionary<string, string>\n    {\n";
  for (const t of tokens) cs += `        ["${t.includes(".") ? t : t + ".Table"}"] = ${t.includes(".") ? t : t + ".Table"},\n`;   // the system dictionary names a table "Entity.Table"
  cs += "    };\n}\n";
  return { sql, cs };
}

const { sql, cs } = generate();
const mode = process.argv[2];
if (mode === "--write") { fs.writeFileSync(outSql, sql); fs.writeFileSync(outCs, cs); console.log("written"); }
else if (mode === "--check") {
  const norm = (s) => s.replace(/\r\n/g, "\n");
  const ok = fs.existsSync(outSql) && fs.existsSync(outCs) && norm(fs.readFileSync(outSql, "utf8")) === sql && norm(fs.readFileSync(outCs, "utf8")) === cs;
  if (!ok) { console.error("generated MFA policy schema differs from the committed files"); process.exit(1); }
  console.log("MFA policy schema files match the generator");
} else { console.error("usage: --write | --check"); process.exit(2); }
