/// <summary>Fiscal-year closing and opening balances (Phase 3.2C S3) against real PostgreSQL; disposable cluster only.</summary>
public abstract class FiscalClosingTestBase : LedgerReportTestBase
{
    protected FiscalYearClosingService Closing { get; private set; } = null!;
    protected FiscalYearClosingManagementService CMg { get; private set; } = null!;
    protected AccountView Equity = null!;
    protected FiscalYearView Year27 = null!;

    protected static PeriodCloseGuard RealGuard() => new([new PendingJournalPeriodCloseProbe(), new PendingAdjustmentsPeriodCloseProbe(), new YearEndClosingPeriodCloseProbe(), new ModuleAbsentPeriodCloseProbe("inventory_valuation_differences")]);

    /// <summary>Year 2026 with: Main sales 1000, Main expense 300, second-branch sales 200 (profit 900: Main 700, B2 200); the equity account is configured; year 2027 exists.</summary>
    protected async Task PrepareClosing(bool configure = true, bool nextYear = true, bool ledger = true)
    {
        await PrepareReports();
        Closing = new FiscalYearClosingService(Resolver, Tx, Journal, RealGuard(), Clock);
        CMg = new FiscalYearClosingManagementService(Rbac, Closing, JMg);
        Equity = await NewAccount("3101", "equity");
        if (nextYear) Year27 = Ok(await Cal.CreateYearAsync(Admin.Id, Company.Id, new FiscalYearInput("FY2027", new DateOnly(2027, 1, 1), "monthly")));
        if (configure) Ok(await Closing.PutSettingsAsync(Admin.Id, Company.Id, 0, new ClosingSettingsInput(Equity.Id, null)));
        if (!ledger) return;
        await Posted(Simple("2026-03-10", 1000m));
        await Posted(Entry("2026-04-05", Dr(Expense.Id, 300m), Cr(Cash.Id, 300m)));
        await Posted(Entry("2026-05-02", Dr(Cash.Id, 200m, null, B2), Cr(Sales.Id, 200m, null, B2)));
    }

    /// <summary>Submits, approves with an independent approver and posts an entry generated by year-end processing.</summary>
    protected async Task<JournalEntryView> PostYearEnd(Guid entryId, Guid? initiator = null)
    {
        var v = await Reload(entryId);
        var s = Ok(await Journal.SubmitAsync(initiator ?? Admin.Id, Company.Id, entryId, v.Header.Revision));
        if (s.Header.Status == JournalStatus.PendingApproval) s = Ok(await Approve(s, Checker1));
        return Ok(await Journal.PostAsync(Checker3, Company.Id, entryId, s.Header.Revision, false));
    }

    protected async Task<FiscalYearClosingView> Close(Guid? year = null)
    {
        var r = await Closing.StartClosingAsync(Admin.Id, Company.Id, year ?? Year.Id);
        Assert.True(r.IsOk, $"{r.Status} {r.Code} {string.Join(",", r.Fields?.Select(f => f.Field + ":" + f.Code) ?? [])}");
        return r.Value!;
    }
    protected async Task<FiscalYearCarryforwardView> Carry(Guid? year = null)
    {
        var r = await Closing.CarryForwardAsync(Admin.Id, Company.Id, year ?? Year.Id);
        Assert.True(r.IsOk, $"{r.Status} {r.Code} {string.Join(",", r.Fields?.Select(f => f.Field + ":" + f.Code) ?? [])}");
        return r.Value!;
    }
    protected async Task<ClosingPreview> Preview(Guid? year = null) => (await Closing.PreviewAsync(Company.Id, year ?? Year.Id))!;
    protected async Task<string?> MessageOf(params string[] statements)
    {
        await using var conn = new Npgsql.NpgsqlConnection(Options.BuildCompanyAdminConnectionString(Company.PhysicalDatabaseName));
        await conn.OpenAsync();
        await using var tx = await conn.BeginTransactionAsync();
        try { foreach (var st in statements) { await using var cmd = new Npgsql.NpgsqlCommand(st, conn, tx); await cmd.ExecuteNonQueryAsync(); } await tx.CommitAsync(); return null; }
        catch (Npgsql.PostgresException ex) { return ex.MessageText; }
    }

    protected static void AssertLines(JournalEntryView v, params (Guid Account, Guid Branch, decimal Debit, decimal Credit)[] expected)
    {
        static IEnumerable<(Guid, Guid, decimal, decimal)> Sorted(IEnumerable<(Guid Account, Guid Branch, decimal Debit, decimal Credit)> l) => l.OrderBy(x => x.Account).ThenBy(x => x.Branch).ThenBy(x => x.Debit).ThenBy(x => x.Credit);
        Assert.Equal(Sorted(expected), Sorted(v.Lines.Select(l => (l.AccountId, l.BranchId, l.BaseDebit, l.BaseCredit))));
    }
}

