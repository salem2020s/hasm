        Assert.DoesNotContain(opening.Lines, l => l.AccountId == Sales.Id || l.AccountId == Expense.Id);                  // revenue and expense start the new year empty
        // Once: the duplicate is refused by the service and by PostgreSQL.
        Assert.Contains((await Closing.CarryForwardAsync(Admin.Id, Company.Id, Year.Id)).Fields!, f => f.Code == "not_carried_forward");
        var spare = await Draft(Entry("2027-01-01", Dr(Cash.Id, 1m), Cr(Sales.Id, 1m)));
