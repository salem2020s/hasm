    }

    [PostgresFact]
    public async Task A_year_cannot_be_closed_twice_even_in_parallel_or_by_direct_writes_and_a_stale_closing_never_posts()
    {
        await PrepareClosing();
        var results = await Task.WhenAll(Enumerable.Range(0, 4).Select(_ => Closing.StartClosingAsync(Admin.Id, Company.Id, Year.Id)));
        Assert.Equal(1, results.Count(r => r.IsOk));
        Assert.All(results.Where(r => !r.IsOk), r => Assert.Equal("closing_blocked", r.Code));
        Assert.Equal(1L, await Sql<long>($"SELECT count(*) FROM {Fc.Table}"));
        var closing = (await Closing.StatusAsync(Company.Id, Year.Id))!.Closings.Single();
        var again = await Closing.StartClosingAsync(Admin.Id, Company.Id, Year.Id);
        Assert.Contains(again.Fields!, f => f.Code == "no_active_closing");
        // A direct writer cannot add a second active closing either.
        var spare = await Draft(Entry("2026-12-31", Dr(Cash.Id, 1m), Cr(Sales.Id, 1m)));
        Assert.Equal("P0001", await Fails($"INSERT INTO {Fc.Table} ({Fc.YearId}, {Fc.Version}, {Fc.NetResult}, {Fc.EquityAccountId}, {Fc.ClosingEntryId}, {Fc.Evidence}, {Fc.CreatedBy}, {Fc.CreatedAtUtc}) VALUES ('{Year.Id}', 2, 0, '{Equity.Id}', '{spare.Header.Id}', '{{}}', '{Admin.Id}', now())"));
        Assert.Equal("P0001", await Fails($"UPDATE {Fc.Table} SET {Fc.NetResult} = 0"));
        Assert.Equal("P0001", await Fails($"DELETE FROM {Fc.Table}"));
        // New profit-and-loss activity after the closing was drafted makes it STALE: it can be submitted but PostgreSQL refuses to post it.
        var entry = await Reload(closing.ClosingEntryId);
        var s = Ok(await Journal.SubmitAsync(Admin.Id, Company.Id, entry.Header.Id, entry.Header.Revision));
        var approved = Ok(await Approve(s, Checker1));
        await Posted(Entry("2026-11-20", Dr(Expense.Id, 50m), Cr(Cash.Id, 50m)));
        var refused = await Journal.PostAsync(Checker3, Company.Id, approved.Header.Id, approved.Header.Revision, false);
        Assert.Equal((ConfigStatus.Conflict, "year_end_stale"), (refused.Status, refused.Code));
        Assert.Equal(JournalStatus.Approved, (await Reload(entry.Header.Id)).Header.Status);                              // nothing changed
        // The year-end plan after a refusal: cancel the stale draft (and the stray draft), then the year can be closed again from the current ledger.
        Ok(await Journal.CancelAsync(Admin.Id, Company.Id, approved.Header.Id, approved.Header.Revision));
        Ok(await Journal.CancelAsync(Maker, Company.Id, spare.Header.Id, spare.Header.Revision));
        var v2 = await Close();
        Assert.Equal(2, v2.Version);
        Assert.Equal(-850m, v2.NetResult);
    }

