        Assert.Equal(JournalStatus.Posted, posted.Header.Status);
        Assert.Equal("carried_forward", (await Closing.StatusAsync(Company.Id, Year.Id))!.Closings.Single().State);
        // 2027 begins with the carried balances and no profit and loss.
        var tb = await Tb("2027-01-01", "2027-12-31");
        Assert.Equal(700m + 200m, Row(tb, Cash.Id).ClosingBalance);
        Assert.Equal(-900m, Row(tb, Equity.Id).ClosingBalance);
        Assert.DoesNotContain(tb.Rows, r => r.AccountId == Sales.Id && r.ClosingBalance != 0);
        Assert.True(tb.Balanced);
    }

