    [PostgresFact]
    public async Task A_correction_reverses_the_opening_balances_then_the_closing_then_closes_again_without_duplicates_and_the_period_probe_blocks_a_stale_year()
    {
        await PrepareClosing();
        var c1 = await Close();
        await PostYearEnd(c1.ClosingEntryId);
        var k1 = await Carry();
        await PostYearEnd(k1.EntryId);
        // A late posting into the still-open year changes its profit and loss: the closing and the opening balances are now STALE (live comparison with the ledger).
        await Posted(Entry("2026-12-15", Dr(Expense.Id, 100m), Cr(Cash.Id, 100m)));
        var stale = (await Closing.StatusAsync(Company.Id, Year.Id))!.Closings.Single();
        Assert.True(stale.Stale);
        var dec = Year.Periods[11];
        await using (var conn = await Resolver.OpenAsync(Company.Id))
        await using (var tx = await conn.BeginTransactionAsync())
        {
            Assert.True(await RealGuard().IsBlockedAsync(Company.Id, new FiscalPeriodView(dec.Id, Year.Id, 12, dec.StartDate, dec.EndDate, FiscalPeriodState.Open, null, 1), conn, tx, default));
        }
        // A new closing is refused until the old one is fully reversed; the reversal of the closing waits for the reversal of the opening balances.
        Assert.Contains((await Closing.StartClosingAsync(Admin.Id, Company.Id, Year.Id)).Fields!, f => f.Code == "no_active_closing");
        var revClosing = Ok(await CMg.ReverseClosingAsync(Admin.Id, Company.Id, Year.Id, new YearEndReversalInput(new DateOnly(2026, 12, 31))));
        var revClosingSubmitted = Ok(await Journal.SubmitAsync(Admin.Id, Company.Id, revClosing.Header.Id, revClosing.Header.Revision));
        if (revClosingSubmitted.Header.Status == JournalStatus.PendingApproval) revClosingSubmitted = Ok(await Approve(revClosingSubmitted, Checker1));
        var tooEarly = await Journal.PostAsync(Checker3, Company.Id, revClosing.Header.Id, revClosingSubmitted.Header.Revision, false);
        Assert.Equal((ConfigStatus.Conflict, "opening_balances_not_reversed"), (tooEarly.Status, tooEarly.Code));
        var revOpening = Ok(await CMg.ReverseOpeningAsync(Admin.Id, Company.Id, Year.Id, new YearEndReversalInput(new DateOnly(2027, 1, 1))));
        var ro = Ok(await Journal.SubmitAsync(Admin.Id, Company.Id, revOpening.Header.Id, revOpening.Header.Revision));
        if (ro.Header.Status == JournalStatus.PendingApproval) ro = Ok(await Approve(ro, Checker1));
        Ok(await Journal.PostAsync(Checker3, Company.Id, revOpening.Header.Id, ro.Header.Revision, false));
        Ok(await Journal.PostAsync(Checker3, Company.Id, revClosing.Header.Id, revClosingSubmitted.Header.Revision, false));
        Assert.Equal("reversed", (await Closing.StatusAsync(Company.Id, Year.Id))!.Closings.Single().State);
        // Version 2 closes from the CURRENT ledger: the year's profit is 800 now (the reversal entries never count as activity), and the carryforward follows with its own key.
        var c2 = await Close();
        Assert.Equal((2, -800m), (c2.Version, c2.NetResult));
        await PostYearEnd(c2.ClosingEntryId);
        var k2 = await Carry();
        await PostYearEnd(k2.EntryId);
        var tb = await Tb("2027-01-01", "2027-12-31");
