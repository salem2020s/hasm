# Creates the disposable test cluster ONCE (refuses if the data directory exists). Not a Windows service.
. "$PSScriptRoot\common.ps1"
Assert-NotDevelopmentCluster
$resume = (Test-Path $SuperFile) -and -not (Test-Path $EnvFile)
if ((Test-Path $DataDir) -and -not $resume) { throw "Data directory already exists: $DataDir (refusing to touch it)." }
foreach ($d in $TestRoot, $LogDir, $SecretsDir) { New-Item -ItemType Directory -Force $d | Out-Null }
Protect-Path $SecretsDir
if ($resume) { $superPw = (Get-Content $SuperFile -Raw).Trim() } else {
$superPw = New-StrongSecret
$pwFile = Join-Path $SecretsDir 'initdb.pw'
Set-Content -NoNewline -Path $pwFile -Value $superPw
try {
    & "$PgBin\initdb.exe" -D $DataDir -U hasm_test_super --pwfile=$pwFile --auth=scram-sha-256 -E UTF8 --locale=C | Out-Null
    if ($LASTEXITCODE -ne 0) { throw 'initdb failed' }
} finally { Remove-Item $pwFile -Force -ErrorAction SilentlyContinue }
Set-Content -Path $SuperFile -Value $superPw -NoNewline
@"

# --- HASM disposable test cluster (never the development cluster) ---
port = $TestPort
listen_addresses = '127.0.0.1'
max_connections = 200
ssl = off
fsync = off
synchronous_commit = off
full_page_writes = off
log_connections = off
"@ | Add-Content -Path (Join-Path $DataDir 'postgresql.conf')
Protect-Path $DataDir
}
& "$PSScriptRoot\start-test-cluster.ps1"

# Roles, identity marker, and the secrets file used by the integration tests.
$env:PGPASSWORD = $superPw
function Psql([string]$Db, [string]$Sql) {
    $out = & "$PgBin\psql.exe" -h 127.0.0.1 -p $TestPort -U hasm_test_super -d $Db -v ON_ERROR_STOP=1 -X -q -c $Sql 2>&1
    if ($LASTEXITCODE -ne 0) { throw "psql failed: $out" }
}
$adminPw = New-StrongSecret; $rolePw = New-StrongSecret; $fingerprint = New-StrongSecret
Psql postgres "CREATE ROLE hasm_test_admin LOGIN CREATEDB NOSUPERUSER NOCREATEROLE NOREPLICATION PASSWORD '$adminPw'"
Psql postgres "CREATE ROLE hasm_test_roleadmin LOGIN CREATEROLE NOSUPERUSER NOCREATEDB NOREPLICATION PASSWORD '$rolePw'"
Psql postgres "CREATE DATABASE $MarkerDb"
Psql $MarkerDb "CREATE TABLE cluster_identity(fingerprint text NOT NULL, purpose text NOT NULL); INSERT INTO cluster_identity VALUES ('$fingerprint','hasm-disposable-test-cluster'); REVOKE ALL ON cluster_identity FROM PUBLIC; GRANT SELECT ON cluster_identity TO hasm_test_admin, hasm_test_roleadmin"
Remove-Item Env:PGPASSWORD
@"
# Generated by new-test-cluster.ps1. Test-only credentials of the disposable cluster on 127.0.0.1:$TestPort. Dot-source before running integration tests.
`$env:HASM_TEST_PG_DISPOSABLE = 'yes-this-server-is-disposable'
`$env:HASM_TEST_PG_CLUSTER_FINGERPRINT = '$fingerprint'
`$env:HASM_TEST_PG_ADMIN_CONNECTION = 'Host=127.0.0.1;Port=$TestPort;Username=hasm_test_admin;Password=$adminPw;Database=postgres;SSL Mode=Disable'
`$env:HASM_TEST_PG_ROLE_ADMIN_CONNECTION = 'Host=127.0.0.1;Port=$TestPort;Username=hasm_test_roleadmin;Password=$rolePw;Database=postgres;SSL Mode=Disable'
"@ | Set-Content -Path $EnvFile
Protect-Path $EnvFile
Write-Host "Test cluster created and running on 127.0.0.1:$TestPort. Secrets: $SecretsDir (owner-only). Fingerprint stored in the marker database."
