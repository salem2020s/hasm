#!/usr/bin/env bash
# Creates the disposable test cluster ONCE (refuses if the data directory exists) and the sourceable env file for the integration tests.
# Linux twin of new-test-cluster.ps1: native cluster, 127.0.0.1:5433 only, owner-only data and secrets outside the repository, random passwords, identity marker database.
. "$(dirname "${BASH_SOURCE[0]}")/common.sh"
assert_safe_locations
umask 077
[[ -d "$(dirname "${TEST_ROOT}")" ]] || die "The parent directory of ${TEST_ROOT} does not exist."
take_lock

# The root must be ABSENT (this script creates it) or be a root this script created earlier (it carries the marker file): a pre-existing directory is never used and never chmod-ed.
resume=no
if [[ -e "${TEST_ROOT}" ]]; then
  [[ -d "${TEST_ROOT}" && ! -L "${TEST_ROOT}" ]] || die "${TEST_ROOT} exists and is not a plain directory; refusing."
  [[ -f "${MARKER_FILE}" ]] || die "${TEST_ROOT} already exists and was not created by new-test-cluster.sh; refusing to use or modify it (choose another HASM_TEST_ROOT)."
  [[ -O "${TEST_ROOT}" ]] || die "${TEST_ROOT} is not owned by the current user; refusing."
  [[ -f "${SUPER_FILE}" && ! -f "${ENV_FILE}" ]] && resume=yes     # an interrupted earlier run that got as far as initdb
  [[ -d "${DATA_DIR}" && "${resume}" == no ]] && die "Data directory already exists: ${DATA_DIR} (refusing to touch it; run destroy-test-cluster.sh first)."
else
  # mkdir (not install -d) fails if the directory appeared in the meantime. The root is traversable (711) so the server account can reach its own 700 data directory.
  mkdir -m 711 "${TEST_ROOT}" || die "Cannot create ${TEST_ROOT}."
  ( umask 077; : > "${MARKER_FILE}" )
fi
[[ "${resume}" == no ]] && port_listening && die "Something already listens on ${TEST_HOST}:${TEST_PORT}; refusing to create a cluster next to it."
install -d -m 700 "${SECRETS_DIR}"
make_pg_dir "${LOG_DIR}"

if [[ "${resume}" == yes ]]; then
  super_pw="$(cat "${SUPER_FILE}")"
else
  make_pg_dir "${DATA_DIR}"
  super_pw="$(new_secret)"
  pw_file="${LOG_DIR}/initdb.pw"
  # the password file is written by the server account (mode 600), used once, and removed
  printf '%s' "${super_pw}" | as_pg sh -c 'umask 077; cat > "$1"' sh "${pw_file}"
  trap 'as_pg rm -f "${pw_file}" 2>/dev/null || true' EXIT
  as_pg "${PG_BIN}/initdb" -D "${DATA_DIR}" -U hasm_test_super --pwfile="${pw_file}" --auth=scram-sha-256 -E UTF8 --locale=C >/dev/null
  as_pg rm -f "${pw_file}"
  ( umask 077; printf '%s' "${super_pw}" > "${SUPER_FILE}" )
  chmod 600 "${SUPER_FILE}"
  conf="${DATA_DIR}/postgresql.conf"
  as_pg sh -c 'cat >> "$1"' sh "${conf}" <<CONF

# --- HASM disposable test cluster (never the development cluster) ---
port = ${TEST_PORT}
listen_addresses = '${TEST_HOST}'
unix_socket_directories = ''
max_connections = 200
ssl = off
fsync = off
synchronous_commit = off
full_page_writes = off
log_connections = off
CONF
fi

"${SCRIPT_DIR}/start-test-cluster.sh"

export PGPASSWORD="${super_pw}"
psql_super() { "${PG_BIN}/psql" -h "${TEST_HOST}" -p "${TEST_PORT}" -U hasm_test_super -d "$1" -v ON_ERROR_STOP=1 -X -q; }   # SQL (with passwords) comes through stdin, never argv
admin_pw="$(new_secret)"; role_pw="$(new_secret)"; fingerprint="$(new_secret)"
psql_super postgres <<SQL
CREATE ROLE hasm_test_admin LOGIN CREATEDB NOSUPERUSER NOCREATEROLE NOREPLICATION PASSWORD '${admin_pw}';
CREATE ROLE hasm_test_roleadmin LOGIN CREATEROLE NOSUPERUSER NOCREATEDB NOREPLICATION PASSWORD '${role_pw}';
CREATE DATABASE ${MARKER_DB};
SQL
psql_super "${MARKER_DB}" <<SQL
CREATE TABLE cluster_identity(fingerprint text NOT NULL, purpose text NOT NULL);
INSERT INTO cluster_identity VALUES ('${fingerprint}', 'hasm-disposable-test-cluster');
REVOKE ALL ON cluster_identity FROM PUBLIC;
GRANT SELECT ON cluster_identity TO hasm_test_admin, hasm_test_roleadmin;
SQL
unset PGPASSWORD

( umask 077; cat > "${ENV_FILE}" <<ENV
# Generated by new-test-cluster.sh. Test-only credentials of the disposable cluster on ${TEST_HOST}:${TEST_PORT}. Source before running integration tests (run-pg-tests.sh does).
export HASM_TEST_PG_DISPOSABLE='yes-this-server-is-disposable'
export HASM_TEST_PG_CLUSTER_FINGERPRINT='${fingerprint}'
export HASM_TEST_PG_ADMIN_CONNECTION='Host=${TEST_HOST};Port=${TEST_PORT};Username=hasm_test_admin;Password=${admin_pw};Database=postgres;SSL Mode=Disable'
export HASM_TEST_PG_ROLE_ADMIN_CONNECTION='Host=${TEST_HOST};Port=${TEST_PORT};Username=hasm_test_roleadmin;Password=${role_pw};Database=postgres;SSL Mode=Disable'
ENV
)
chmod 600 "${ENV_FILE}"
echo "Test cluster created and running on ${TEST_HOST}:${TEST_PORT}. Secrets: ${SECRETS_DIR} (owner-only). Fingerprint stored in the marker database."
